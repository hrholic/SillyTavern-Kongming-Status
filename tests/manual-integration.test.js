import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';
const wait = () => new Promise(resolve => setTimeout(resolve, 90));

test('save/edit/cancel/delete and reload rules; current/future chats, disable and exclusions preserve originals', async () => {
    const fixture = await readFile(new URL('./fixture.html', import.meta.url), 'utf8');
    const dom = new JSDOM(fixture, { url: 'http://localhost/', runScripts: 'dangerously', pretendToBeVisual: true }), w = dom.window;
    for (const key of ['document', 'MutationObserver', 'SillyTavern']) globalThis[key] = w[key];
    globalThis.getComputedStyle = w.getComputedStyle.bind(w);
    globalThis.requestAnimationFrame = w.requestAnimationFrame.bind(w);
    globalThis.cancelAnimationFrame = w.cancelAnimationFrame.bind(w);
    globalThis.matchMedia = () => ({ matches: false });
    const raw = '<my_panel>今天已经完成阅读</my_panel><content>独立正文内容</content>';
    w.chatFixture.push({ mes: raw });
    const mes = w.document.createElement('div'); mes.className = 'mes'; mes.setAttribute('mesid', '2'); mes.setAttribute('is_user', 'false');
    mes.innerHTML = '<div class="mes_text"><section id="manual-target">今天已经完成阅读</section><p id="manual-story">独立正文内容</p></div>';
    w.document.querySelector('#chat').append(mes);
    const target = mes.querySelector('section');
    let clicks = 0; target.addEventListener('click', () => clicks++);
    const plugin = await import('../index.js?manual-integration');
    let reloaded;
    const $ = selector => w.document.querySelector(selector);
    const change = input => input.dispatchEvent(new w.Event('change', { bubbles: true }));
    const button = label => [...w.document.querySelectorAll('button')].find(node => node.getAttribute('aria-label') === label);
    const saveRule = () => $('[data-kms-rule-action="save"]').click();
    try {
        await wait(); await wait(); assert.equal(target.className, '');
        $('[data-kms-rule="start"]').value = '<my_panel>'; change($('[data-kms-rule="start"]'));
        assert.equal($('[data-kms-rule="end"]').value, '</my_panel>');
        saveRule(); await wait(); assert.ok(target.classList.contains('kms-card'));
        assert.equal(w.SillyTavern.getContext().extensionSettings.kongming_status.manualRules.length, 1);
        saveRule(); await wait(); assert.equal(w.SillyTavern.getContext().extensionSettings.kongming_status.manualRules.length, 1);
        button('修改 <my_panel> 规则').click(); $('[data-kms-rule="start"]').value = '<other>';
        [...w.document.querySelectorAll('button')].find(n => n.textContent === '取消修改').click();
        assert.equal(w.SillyTavern.getContext().extensionSettings.kongming_status.manualRules[0].start, '<my_panel>');
        button('修改 <my_panel> 规则').click();
        $('[data-kms-rule="start"]').value = '<other>'; $('[data-kms-rule="end"]').value = '</other>';
        saveRule(); await wait(); assert.equal(target.className, '');
        button('修改 <other> 规则').click();
        $('[data-kms-rule="start"]').value = '<my_panel>'; $('[data-kms-rule="end"]').value = '</my_panel>';
        saveRule(); await wait(); assert.ok(target.classList.contains('kms-card'));
        plugin.onDisable(); reloaded = await import('../index.js?manual-reload'); await wait(); await wait();
        assert.ok(target.classList.contains('kms-card')); assert.equal($('.kms-rule-pair').textContent, '<my_panel> … </my_panel>');
        const next = mes.cloneNode(true); next.querySelector('section').className = ''; next.querySelector('section').id = 'next-manual-target';
        next.setAttribute('mesid', '3'); w.chatFixture.push({ mes: raw }); w.document.querySelector('#chat').replaceChildren(next);
        await wait(); await wait(); assert.ok(next.querySelector('section').classList.contains('kms-card'));
        $('[data-kms-setting="excluded"]').value = 'my_panel'; change($('[data-kms-setting="excluded"]')); await wait();
        assert.equal(next.querySelector('section').className, '');
        $('[data-kms-setting="excluded"]').value = ''; change($('[data-kms-setting="excluded"]')); await wait();
        $('[data-kms-setting="enabled"]').checked = false; change($('[data-kms-setting="enabled"]')); await wait();
        assert.equal(next.querySelector('section').className, '');
        $('[data-kms-setting="enabled"]').checked = true; change($('[data-kms-setting="enabled"]')); await wait();
        button('删除 <my_panel> 规则').click(); await wait();
        assert.equal(next.querySelector('section').className, '');
        assert.deepEqual(w.SillyTavern.getContext().extensionSettings.kongming_status.manualRules, []);
        target.click(); assert.equal(clicks, 1); assert.equal(w.chatFixture[2].mes, raw); assert.equal(w.chatFixture[3].mes, raw);
        assert.equal(next.querySelector('p').textContent, '独立正文内容');
    } finally { reloaded?.onDisable(); plugin.onDisable(); dom.window.close(); }
});
